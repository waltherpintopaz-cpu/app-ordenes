-- Reprogramar orden: cambiar hora (hoy), cambiar dia+hora o dejar "Por coordinar"
-- (sin fecha, el cliente se comunicara). La orden NO se liquida: sigue Pendiente.
-- Queda historial, contador y un mensaje automatico en el chat de la orden
-- (el trigger de push del chat avisa a la oficina y al equipo del tecnico).

alter table public.ordenes add column if not exists por_coordinar_desde timestamptz;
alter table public.ordenes add column if not exists reprogramaciones integer not null default 0;

alter table public.whatsapp_config add column if not exists template_reprogramada text;
alter table public.whatsapp_config add column if not exists template_por_coordinar text;

create table if not exists public.ordenes_reprogramaciones (
  id bigint generated by default as identity primary key,
  orden_id bigint not null,
  tipo text not null,                -- 'hora' | 'fecha' | 'sin_fecha'
  fecha_anterior date,
  hora_anterior time,
  fecha_nueva date,
  hora_nueva time,
  motivo text,
  nota text,
  autor text,
  autor_rol text,
  created_at timestamptz not null default now()
);
create index if not exists ordenes_reprogramaciones_orden_idx on public.ordenes_reprogramaciones (orden_id, created_at desc);

alter table public.ordenes_reprogramaciones enable row level security;
drop policy if exists ordenes_reprogramaciones_leer on public.ordenes_reprogramaciones;
create policy ordenes_reprogramaciones_leer on public.ordenes_reprogramaciones for select using (true);
grant select on public.ordenes_reprogramaciones to anon, authenticated;

create or replace function public.reprogramar_orden(
  p_orden_id bigint,
  p_tipo text,
  p_fecha date,
  p_hora time,
  p_motivo text,
  p_nota text,
  p_autor text,
  p_autor_rol text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  o public.ordenes%rowtype;
  v_estado text;
  v_dias text[] := array['domingo','lunes','martes','miércoles','jueves','viernes','sábado'];
  v_texto text;
  v_det text;
begin
  if p_tipo not in ('hora','fecha','sin_fecha') then
    raise exception 'Tipo de reprogramacion invalido';
  end if;
  if p_tipo <> 'sin_fecha' and (p_fecha is null or p_hora is null) then
    raise exception 'Falta la nueva fecha u hora';
  end if;

  select * into o from public.ordenes where id = p_orden_id for update;
  if not found then raise exception 'Orden no encontrada'; end if;

  v_estado := lower(coalesce(o.estado, ''));
  if v_estado like '%liquidad%' or v_estado like '%finaliz%' or v_estado like '%cerrad%' or v_estado like '%complet%' then
    raise exception 'La orden ya esta liquidada';
  end if;

  update public.ordenes set
    estado = case when v_estado like '%pendient%' then o.estado else 'Pendiente' end,
    fecha_actuacion = case when p_tipo = 'sin_fecha' then o.fecha_actuacion else p_fecha end,
    hora = case when p_tipo = 'sin_fecha' then o.hora else p_hora end,
    por_coordinar_desde = case when p_tipo = 'sin_fecha' then now() else null end,
    atendida_sin_liquidar_en = null,
    reprogramaciones = coalesce(o.reprogramaciones, 0) + 1
  where id = p_orden_id;

  insert into public.ordenes_reprogramaciones
    (orden_id, tipo, fecha_anterior, hora_anterior, fecha_nueva, hora_nueva, motivo, nota, autor, autor_rol)
  values
    (p_orden_id, p_tipo, o.fecha_actuacion, o.hora,
     case when p_tipo = 'sin_fecha' then null else p_fecha end,
     case when p_tipo = 'sin_fecha' then null else p_hora end,
     nullif(trim(coalesce(p_motivo, '')), ''), nullif(trim(coalesce(p_nota, '')), ''), p_autor, p_autor_rol);

  v_det := coalesce(nullif(trim(coalesce(p_motivo, '')), ''), 'Sin motivo')
        || case when nullif(trim(coalesce(p_nota, '')), '') is not null then ' · ' || trim(p_nota) else '' end;

  if p_tipo = 'sin_fecha' then
    v_texto := '⏸ Orden por coordinar (sin fecha, el cliente se comunicará)' || E'\n' || 'Motivo: ' || v_det;
  elsif p_tipo = 'hora' then
    v_texto := '🕒 Cambio de hora: ' || coalesce(to_char(o.hora, 'HH24:MI'), '—') || ' → ' || to_char(p_hora, 'HH24:MI')
            || ' (' || v_dias[extract(dow from p_fecha)::int + 1] || ' ' || to_char(p_fecha, 'DD/MM') || ')'
            || E'\n' || 'Motivo: ' || v_det;
  else
    v_texto := '📅 Reprogramada para ' || v_dias[extract(dow from p_fecha)::int + 1] || ' ' || to_char(p_fecha, 'DD/MM')
            || ' · ' || to_char(p_hora, 'HH24:MI') || E'\n' || 'Motivo: ' || v_det;
  end if;

  insert into public.chat_ordenes_mensajes (orden_id, texto, autor, autor_rol)
  values (p_orden_id, v_texto, coalesce(nullif(p_autor, ''), 'Sistema'), p_autor_rol);

  return jsonb_build_object(
    'ok', true,
    'reprogramaciones', coalesce(o.reprogramaciones, 0) + 1,
    'fecha_actuacion', case when p_tipo = 'sin_fecha' then o.fecha_actuacion else p_fecha end,
    'hora', case when p_tipo = 'sin_fecha' then o.hora else p_hora end
  );
end;
$$;

grant execute on function public.reprogramar_orden(bigint, text, date, time, text, text, text, text) to anon, authenticated;

notify pgrst, 'reload schema';
