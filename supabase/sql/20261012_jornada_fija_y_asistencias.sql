-- Jornada fija (duracion configurable, 9h por defecto) con aprobacion de
-- cierre anticipado + permisos de medio dia pre-autorizados -- base para el
-- modulo de Asistencias en el panel web.
--
-- Mientras hay una solicitud de cierre anticipado pendiente, el turno sigue
-- "activo" (fin sigue null) -- el rastreo del tecnico no se corta solo, que
-- es la intencion: no puede pausar hasta que alguien lo apruebe o se
-- cumplan las horas programadas.

alter table public.tecnico_turnos add column if not exists duracion_horas numeric default 9;
alter table public.tecnico_turnos add column if not exists fin_programado timestamptz;
alter table public.tecnico_turnos add column if not exists cierre_anticipado_solicitado boolean default false;
alter table public.tecnico_turnos add column if not exists cierre_anticipado_motivo text;
alter table public.tecnico_turnos add column if not exists cierre_anticipado_solicitado_en timestamptz;
alter table public.tecnico_turnos add column if not exists cierre_anticipado_estado text; -- null | 'pendiente' | 'aprobado' | 'rechazado'
alter table public.tecnico_turnos add column if not exists cierre_anticipado_resuelto_por text;
alter table public.tecnico_turnos add column if not exists cierre_anticipado_resuelto_en timestamptz;

comment on column public.tecnico_turnos.duracion_horas is
  'Duracion esperada de la jornada en horas (9 por defecto, o lo que diga tecnico_permisos_dia para ese dia).';
comment on column public.tecnico_turnos.fin_programado is
  'inicio + duracion_horas -- antes de esta hora, "Finalizar jornada" crea una solicitud en vez de cerrar directo.';
comment on column public.tecnico_turnos.cierre_anticipado_estado is
  'pendiente: esperando que un admin apruebe/rechace. aprobado: el admin cerro el turno antes de tiempo. rechazado: el tecnico sigue trabajando, puede volver a pedir.';

-- Permiso de medio dia (o cualquier duracion distinta a la jornada normal)
-- pre-autorizado por un admin ANTES de que el tecnico inicie jornada ese
-- dia -- asi no necesita pedir aprobacion en caliente si ya se sabia que
-- iba a salir mas temprano (ej. cita medica).
create table if not exists public.tecnico_permisos_dia (
  id bigint generated by default as identity primary key,
  tecnico_id text not null,
  tecnico_nombre text,
  fecha date not null,
  duracion_horas numeric not null,
  motivo text,
  creado_por text,
  creado_en timestamptz not null default now(),
  unique (tecnico_id, fecha)
);

alter table public.tecnico_permisos_dia enable row level security;
drop policy if exists "tecnico_permisos_dia_abierto" on public.tecnico_permisos_dia;
create policy "tecnico_permisos_dia_abierto" on public.tecnico_permisos_dia for all using (true) with check (true);
