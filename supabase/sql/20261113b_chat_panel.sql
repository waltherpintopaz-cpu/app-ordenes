-- Pantalla de Chats: "Lo atiendo yo" y respuestas rapidas editables por la oficina.

-- Quien esta atendiendo cada chat (clave = "orden:123" o "tecnico:Nombre").
-- Vence sola a las 4 horas (el panel ignora las mas viejas).
create table if not exists public.chat_atencion (
  clave text primary key,
  usuario text not null,
  desde timestamptz not null default now()
);
alter table public.chat_atencion enable row level security;
drop policy if exists chat_atencion_todo on public.chat_atencion;
create policy chat_atencion_todo on public.chat_atencion for all using (true) with check (true);
grant select, insert, update, delete on public.chat_atencion to anon, authenticated;

-- Respuestas rapidas propias. contexto: 'oficina' | 'tecnico' | 'cliente'.
create table if not exists public.chat_respuestas_rapidas (
  id bigint generated by default as identity primary key,
  texto text not null,
  contexto text not null default 'oficina',
  creado_por text,
  created_at timestamptz not null default now()
);
alter table public.chat_respuestas_rapidas enable row level security;
drop policy if exists chat_respuestas_rapidas_todo on public.chat_respuestas_rapidas;
create policy chat_respuestas_rapidas_todo on public.chat_respuestas_rapidas for all using (true) with check (true);
grant select, insert, update, delete on public.chat_respuestas_rapidas to anon, authenticated;

-- En vivo (Realtime) para que todas las gestoras vean quien atiende.
do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'chat_atencion') then
    alter publication supabase_realtime add table public.chat_atencion;
  end if;
end $$;
alter table public.chat_atencion replica identity full;

notify pgrst, 'reload schema';
